// The WRITE PATH: what "Add to Open WebUI" actually does.
//
// THE DECISION, and why. Adding a model to Open WebUI's picker is a configuration change, and
// configuration changes go through a play. Two designs were available:
//
//   (a) the app emits DESIRED STATE; an Ansible play applies it.      <- CHOSEN
//   (b) the app POSTs to the gateway's /model/new directly.
//
// (a) wins on three counts:
//
//   1. THE REPO IS THE SOURCE OF TRUTH. `litellm_openrouter_models` is the declared picker list,
//      curated BY HAND on purpose — choosing which models a human sees is a preference, not a
//      mirror of an upstream catalogue. Writing to the gateway's database instead would put
//      configuration somewhere a rebuild does not reproduce, and the repo and the DB would
//      diverge with nothing reporting it.
//
//   2. NO CREDENTIAL IN THE BROWSER. /model/new needs an admin credential, and an admin credential
//      can also spend real money. Minting a scoped virtual key would narrow
//      that, but the browser would still hold a writable gateway credential served from a
//      static file — i.e. readable by anyone who can reach the app. Emitting a text file needs
//      no credential at all, which is a smaller thing to get right.
//
//   3. IT STAYS REVIEWABLE. The output is a diff against a file in git, so what changed, who
//      changed it and why is visible in the normal way. With `store_model_in_db` enabled, a
//      /model/new registration PERSISTS across restarts, so (b)'s mistakes would be durable
//      and invisible.
//
// What the checkbox therefore means: STAGE this model. The app produces the exact YAML block to
// paste into the inventory (and a copy button), then the existing deploy play applies it. The
// app never mutates anything by itself and holds no credential — it is a read-only view plus a
// clipboard.
//
// The cost of (a) is honest and worth stating: it is NOT one click. Someone pastes the block,
// commits, and runs the play. That is the intended friction — the same friction that makes the
// declared list reviewable — and the UI says so rather than implying the checkbox deployed
// anything.

import { assertSafeModelId } from "./ids";
import { OPENROUTER_PREFIX } from "./models";
import type { Model } from "./models";

/**
 * Models that can be staged at all.
 *
 * Only `openrouter/*` ids belong in `litellm_openrouter_models`: that variable exists purely
 * because OpenRouter cannot enumerate. An anthropic or openai model is ALREADY enumerated by
 * its provider wildcard and self-updates as the provider ships models, so adding one to this
 * list would be a hand-maintained copy of a list that maintains itself. The UI disables the
 * checkbox for those and says why.
 */
export function isStageable(m: Model): boolean {
  return m.provider === "openrouter";
}

/**
 * Why a model cannot be staged, for the UI to show. Null when it can.
 */
export function stageBlockedReason(m: Model): string | null {
  if (m.inPicker) {
    return "Already declared in litellm_openrouter_models — it is in the picker today.";
  }
  if (!isStageable(m)) {
    return `Already enumerated via the ${m.provider}/* wildcard, so it is pickable without being declared. Listing it would hand-maintain a list that maintains itself.`;
  }
  return null;
}

/**
 * Render the full desired-state block for the inventory.
 *
 * The WHOLE list is emitted, not just the additions, because the variable is a declaration of
 * the complete desired set — a partial block pasted over it would silently REMOVE every model
 * it omitted. Emitting the full list makes the paste a replacement, which is what the reader
 * expects a declarative block to be.
 */
export function renderDesiredState(declared: string[], staged: string[]): string {
  // Every id is checked again HERE, not only when the snapshot is loaded: this is the function
  // whose output a human pastes into configuration, so it refuses an unsafe id (src/ids.ts)
  // whatever its caller did, and quotes every id it emits.
  for (const id of [...declared, ...staged]) assertSafeModelId(id);
  // Sorted and de-duplicated so the output is stable: a block whose order churns produces a
  // noisy diff that obscures the one line that actually changed.
  const all = [...new Set([...declared, ...staged])].sort();
  const added = new Set(staged.filter((s) => !declared.includes(s)));

  const lines: string[] = [
    "# litellm_openrouter_models — the OpenRouter models surfaced in Open WebUI's picker.",
    "#",
    "# Generated by the model explorer. Paste this over the existing block in the inventory",
    "# that configures the gateway, then re-run the play that applies service_litellm.",
    "#",
    "# BEFORE committing a NEW id, prove it completes a real request — a catalogue entry is not a",
    "# working route, and a plausible-looking id may not exist upstream.",
    "litellm_openrouter_models:",
  ];
  for (const id of all) {
    lines.push(`  - ${JSON.stringify(id)}${added.has(id) ? "   # ADDED by the model explorer" : ""}`);
  }
  return lines.join("\n") + "\n";
}

/** The bare ids, for a shortlist of upstream ids (for example, to probe each one). */
export function bareIds(ids: string[]): string[] {
  return ids.map((i) => (i.startsWith(OPENROUTER_PREFIX) ? i.slice(OPENROUTER_PREFIX.length) : i));
}
